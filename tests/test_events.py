@pytest.mark.parametrize("text,expect,cat", CASES, ids=[c[0][:30] for c in CASES])
def test_parse_post(text, expect, cat):
    ev = parse_post(post(text), CH, TZ)
    if expect is None:
        assert ev is None
        return
    assert ev is not None
    day, h, m = expect
    d, mo = day if isinstance(day, tuple) else (day, 9)
    start = ev["starts_at"]
    assert (start.day, start.month, start.hour, start.minute) == (d, mo, h, m)
    assert ev["has_time"]
    assert ev["category"] == cat


def test_time_not_confused_with_date_or_price():
    assert event_time("27.09 цена 250.000 донгов, начало в 19:30") == (19, 30)
    assert event_time("27 сентября, 12.00 север") is None or event_time("27 сентября, 12.00 север") == (12, 0)


def test_weekday_relative():
    posted = datetime(2026, 9, 26, 10, 0, tzinfo=TZ)  # суббота
    assert event_date("в среду в 9:00 утренняя практика", posted).day == 30
    assert event_date("мафия 2 мафии за вечер, завтра старт", posted).day == 27


def test_collect_dedup_and_votes():
    db = DB(":memory:")
    evs = Events(db)
    exit_text = ("26 сентября — вечеринка EXIT в центре города на саундсистеме REDALERT.\nМощнейший звук в городе.\n"
                 "Вход свободный. Zone 86 | Sep 26 | 9PM–5AM")
    feeds = {
        -1001724508141: [post(exit_text, 7991, "2026-09-25T15:18:27+00:00")],
        -1001518850696: [post(exit_text, 1903, "2026-09-22T09:21:04+00:00")],
    }

    async def fetch(chat_id, limit):
        return feeds.get(chat_id, [])

    stats = asyncio.run(evs.collect(TZ, fetch=fetch, pause=0))
    assert stats["events"] == 1  # один EXIT на два канала
    stats = asyncio.run(evs.collect(TZ, fetch=fetch, pause=0))
    assert stats["posts"] == 0  # второй проход не перечитывает старое
    [ev] = evs.upcoming(datetime(2026, 9, 26, tzinfo=TZ), datetime(2026, 9, 27, tzinfo=TZ))
    assert ev["category"] == "вечеринка"
    evs.vote(ev["id"], up=False)
    assert evs.weight("вечеринка") < 1.0
    assert evs.upcoming(datetime(2026, 9, 26, tzinfo=TZ), datetime(2026, 9, 27, tzinfo=TZ)) == []
    assert parse_iso(ev["starts_at"]).astimezone(TZ).day == 26
